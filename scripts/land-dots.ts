/**
 * Precomputes the globe's land dots (destination-love, marketing globe) from Natural Earth
 * 1:110m land (world-atlas, public domain): for a Fibonacci lattice of N points on the sphere,
 * one bit per point — land or sea. Three lattices (one per quality tier) as base64 bitsets.
 *
 *   pnpm tsx scripts/land-dots.ts   → writes src/lib/land-dots.data.ts
 */
import { readFile, writeFile } from 'node:fs/promises';
import { geoContains } from 'd3-geo';
import { feature } from 'topojson-client';
import type { GeometryCollection, Topology } from 'topojson-specification';
import { LAND_LATTICE, latticePoint } from '../src/lib/land-dots';

async function main() {
  const topo = JSON.parse(await readFile('node_modules/world-atlas/land-110m.json', 'utf8')) as Topology<{ land: GeometryCollection }>;
  const land = feature(topo, topo.objects.land);
  const out: Record<string, string> = {};
  for (const [tier, n] of Object.entries(LAND_LATTICE)) {
    const bits = new Uint8Array(Math.ceil(n / 8));
    let count = 0;
    for (let i = 0; i < n; i++) {
      const { lat, lon } = latticePoint(i, n);
      if (geoContains(land, [lon, lat])) {
        bits[i >> 3]! |= 1 << (i & 7);
        count++;
      }
    }
    out[tier] = Buffer.from(bits).toString('base64');
    console.log(`${tier}: ${n} lattice points, ${count} on land, ${bits.length} bytes`);
  }
  const body = `// Generated by scripts/land-dots.ts from Natural Earth 1:110m land (world-atlas, public domain). Do not edit.
export const LAND_BITS: Record<'high' | 'medium' | 'low', string> = ${JSON.stringify(out, null, 2)};
`;
  await writeFile('src/lib/land-dots.data.ts', body);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
